"""The replication's report (PREREG.md section 7): every number and figure comes from the raw outputs. Uses only the
standard library and matplotlib. A trajectory that has not finished is reported as missing.

  python analysis/make_replication_report.py results/replication/raw results/raw results/replication
"""
import gzip
import json
import os
import statistics
import sys

sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
from selfedit.metrics import paired  # noqa: E402

RAW, MAIN, RES = sys.argv[1], sys.argv[2], sys.argv[3]
os.makedirs(os.path.join(RES, "figures"), exist_ok=True)
REP = os.path.join(RAW, "replication")
RULES = ("C2_finished_only", "C1_answer_key")
SHORT = {"C2_finished_only": "C2 (kept the answers it finished)", "C1_answer_key": "C1 (kept the answers the key marks right)"}


def rd(path):
    with gzip.open(path, "rt", encoding="utf-8") as f:
        return [json.loads(x) for x in f]


def has(path):
    return os.path.exists(path)


def acc(rs):
    return sum(r["correct"] for r in rs) / len(rs)


def cut(rs):
    return sum(r["finish"] == "length" for r in rs) / len(rs)


def ending(rs):
    finished = [r for r in rs if r["finish"] == "stop"]
    right = sum(r["correct"] for r in finished)
    return {"finished": len(finished), "finished_right": right, "finished_wrong": len(finished) - right,
            "right_among_finished": right / len(finished) if finished else None,
            "right_but_cut": sum(r["correct"] for r in rs if r["finish"] != "stop")}


def pct(x, signed=False):
    if x is None:
        return "-"
    return f"{100 * x:+.1f}" if signed else f"{100 * x:.1f}"


def gain_txt(p):
    z = "undefined" if p["z"] is None else f"{p['z']:.2f}"
    return f"{100 * p['gain']:+.1f} (SE {100 * p['se']:.1f}, z {z})"


def with_salt(rows, salt):
    return [dict(r, id=f"{salt}|{r['id']}") for r in rows]


# ------------------------------------------------------------------ load
old_base = rd(os.path.join(RAW, "test", "unedited.jsonl.gz"))
old_astra = rd(os.path.join(RAW, "test", "astra_positive_control.jsonl.gz"))
main_base = rd(os.path.join(MAIN, "test", "unedited.jsonl.gz"))
main_astra = rd(os.path.join(MAIN, "test", "astra_positive_control.jsonl.gz"))
fresh_base = rd(os.path.join(REP, "fresh_test", "unedited.jsonl.gz"))
fresh_astra = rd(os.path.join(REP, "fresh_test", "astra_positive_control.jsonl.gz"))
T = {}   # (rule, seed) -> {"traj": ..., "old": {round: rows}, "fresh": {round: rows}}
for rule in RULES:
    for seed in (1, 2, 3):
        d = os.path.join(REP, f"{rule}_s{seed}")
        tp = os.path.join(d, "trajectory.json")
        if not has(tp):
            continue
        traj = json.load(open(tp, encoding="utf-8"))
        rounds = [r["round"] for r in traj["rounds"]]
        T[(rule, seed)] = {"traj": traj, "rounds": rounds,
                           "old": {r: rd(os.path.join(d, f"test_round{r}.jsonl.gz")) for r in rounds},
                           "fresh": {r: rd(os.path.join(d, f"fresh_test_round{r}.jsonl.gz")) for r in rounds
                                     if has(os.path.join(d, f"fresh_test_round{r}.jsonl.gz"))}}
main_c = {}
for rule in RULES:
    d = os.path.join(MAIN, "arm_c", rule)
    main_c[rule] = {r: rd(os.path.join(d, f"test_round{r}.jsonl.gz")) for r in (1, 2, 3)}

S = {"main_run": {}, "reproduction": {}, "old_problems": {}, "fresh_problems": {}, "rounds_3_to_6": {}, "bug_check": {}, "weights": {}}
L = ["# RESULTS of the replication (generated by analysis/make_replication_report.py; do not edit by hand)", "",
     "Plan and predictions: [PREREG.md section 7](../../PREREG.md). Training: Arm C's recipe with the audit's fix. "
     "A gain is against the unedited model of this replication, on the same problems. 'Old problems' are the main run's "
     "200 test problems; 'fresh problems' are 200 test problems no earlier measurement used.", ""]

# ------------------------------------------------------------------ reproduction of the two reference models
L += ["## 1. The unedited model and the positive control, measured again", "",
      "| model | main run | this run | answers word for word the same as the main run's | fresh problems |", "|---|---|---|---|---|"]
for name, new, old, fresh in (("unedited", old_base, main_base, fresh_base), ("positive control", old_astra, main_astra, fresh_astra)):
    m = {r["id"]: r["text"] for r in old}
    same = sum(m.get(r["id"]) == r["text"] for r in new)
    S["reproduction"][name] = {"main_run": acc(old), "this_run": acc(new), "identical_texts": same, "n": len(new),
                               "cut": cut(new), "ending": ending(new), "fresh": acc(fresh), "fresh_cut": cut(fresh), "fresh_ending": ending(fresh)}
    L.append(f"| {name} | {pct(acc(old))}% | {pct(acc(new))}% | {same} of {len(new)} | {pct(acc(fresh))}% |")
pc_old, pc_fresh = paired(old_base, old_astra), paired(fresh_base, fresh_astra)
S["reproduction"]["positive_control_gain"] = {"old": pc_old, "fresh": pc_fresh}
L += ["", f"Positive control's gain: {gain_txt(pc_old)} on the old problems, {gain_txt(pc_fresh)} on the fresh problems.", ""]

# ------------------------------------------------------------------ every round on the old problems
L += ["## 2. Every round on the 200 old problems", ""]
for rule in RULES:
    seeds = sorted(s for r, s in T if r == rule)
    L += [f"### {SHORT[rule]}", "",
          "| seed | round | answers kept (of 256) | optimizer steps | last batch | accuracy | gain vs unedited | vs previous round | cut at the cap | finished | finished, wrong |",
          "|---|---|---|---|---|---|---|---|---|---|---|"]
    for seed in seeds:
        t = T[(rule, seed)]
        S["old_problems"].setdefault(rule, {})[str(seed)] = {"0": {"acc": acc(old_base), "cut": cut(old_base), **ending(old_base)}}
        prev = old_base
        e0 = ending(old_base)
        L.append(f"| {seed} | 0 (unedited) | - | - | - | {pct(acc(old_base))} | - | - | {pct(cut(old_base))} | {e0['finished']} | {e0['finished_wrong']} |")
        for row in t["traj"]["rounds"]:
            r = row["round"]
            rows = t["old"][r]
            g, d = paired(old_base, rows), paired(prev, rows)
            e = ending(rows)
            steps = row["training"].get("optimizer_steps", 0)
            kept = row["kept"]
            S["old_problems"][rule][str(seed)][str(r)] = {"acc": acc(rows), "cut": cut(rows), "gain": g, "vs_previous": d, "kept": kept,
                                                          "kept_correct": row["kept_correct"], "steps": steps, **e}
            L.append(f"| {seed} | {r} | {kept} ({row['kept_correct']} right) | {steps} | {(kept - 1) % 8 + 1 if kept else '-'} | {pct(acc(rows))} | "
                     f"{gain_txt(g)} | {pct(d['gain'], True)} (SE {pct(d['se'])}) | {pct(cut(rows))} | {e['finished']} | {e['finished_wrong']} |")
            prev = rows
    L.append("")
    means = []
    for r in range(0, 7):
        vals = [acc(old_base) if r == 0 else acc(T[(rule, s)]["old"][r]) for s in seeds if r == 0 or r in T[(rule, s)]["old"]]
        if vals and len(vals) == len(seeds):
            means.append((r, statistics.mean(vals), min(vals), max(vals)))
    S["old_problems"].setdefault(rule, {})["mean_by_round"] = {str(r): {"mean": m, "min": a, "max": b} for r, m, a, b in means}
    L += ["| round | mean accuracy over the seeds | smallest | largest |", "|---|---|---|---|"]
    L += [f"| {r} | {pct(m)} | {pct(a)} | {pct(b)} |" for r, m, a, b in means]
    L.append("")
main_line = {rule: [acc(main_base)] + [acc(main_c[rule][r]) for r in (1, 2, 3)] for rule in RULES}
S["main_run"] = {"accuracy_by_round": main_line, "unedited": acc(main_base), "positive_control": acc(main_astra)}
L += ["The main run, for comparison (old divisor, one trajectory): " + "; ".join(
      f"{rule.split('_')[0]} " + " -> ".join(pct(x) for x in main_line[rule]) for rule in RULES) + ".", ""]

# ------------------------------------------------------------------ fresh problems, and round 6 against round 3
L += ["## 3. Fresh problems, and round 6 against round 3", "",
      "| rule | seed | round | accuracy, fresh | gain vs unedited, fresh | cut, fresh | finished, wrong (fresh) |", "|---|---|---|---|---|---|---|"]
for rule in RULES:
    for seed in sorted(s for r, s in T if r == rule):
        for r, rows in sorted(T[(rule, seed)]["fresh"].items()):
            g, e = paired(fresh_base, rows), ending(rows)
            S["fresh_problems"].setdefault(rule, {}).setdefault(str(seed), {})[str(r)] = {"acc": acc(rows), "gain": g, "cut": cut(rows), **e}
            L.append(f"| {rule.split('_')[0]} | {seed} | {r} | {pct(acc(rows))} | {gain_txt(g)} | {pct(cut(rows))} | {e['finished_wrong']} |")
L += ["", f"Unedited on the fresh problems: {pct(acc(fresh_base))}%; positive control: {pct(acc(fresh_astra))}%.", "",
      "| rule | seed | round 6 minus round 3: old problems | fresh problems | all 400 |", "|---|---|---|---|---|"]
for rule in RULES:
    for seed in sorted(s for r, s in T if r == rule):
        t = T[(rule, seed)]
        if 3 in t["old"] and 6 in t["old"] and 3 in t["fresh"] and 6 in t["fresh"]:
            o, f = paired(t["old"][3], t["old"][6]), paired(t["fresh"][3], t["fresh"][6])
            a = paired(with_salt(t["old"][3], "o") + with_salt(t["fresh"][3], "f"), with_salt(t["old"][6], "o") + with_salt(t["fresh"][6], "f"))
            S["rounds_3_to_6"].setdefault(rule, {})[str(seed)] = {"old": o, "fresh": f, "all_400": a}
            L.append(f"| {rule.split('_')[0]} | {seed} | {gain_txt(o)} | {gain_txt(f)} | {gain_txt(a)} |")
L.append("")

# ------------------------------------------------------------------ what the audit's fix changed
L += ["## 4. What the audit's fix changed (round 1 of seed 1; same start, same kept answers)", ""]
for rule in RULES:
    p = os.path.join(REP, f"{rule}_s1", "bug_check.json")
    if not has(p) or 1 not in T.get((rule, 1), {"old": {}})["old"]:
        continue
    b = json.load(open(p, encoding="utf-8"))
    corrected = T[(rule, 1)]["old"][1]
    row = {"kept": b["kept"], "last_batch": b["last_batch"], "corrected_accuracy": acc(corrected),
           "same_seed_again": b["same_seed_again"]["difference_from_corrected"]}
    L += [f"### {SHORT[rule]}: {b['kept']} answers, last batch {b['last_batch']}", "",
          f"Trained again with the same seed: {b['same_seed_again']['difference_from_corrected']['entries_changed']:,} weights differ.", "",
          "| version | accuracy | difference from the corrected training | weights that differ from the corrected training |", "|---|---|---|---|",
          f"| corrected | {pct(acc(corrected))} | - | - |"]
    for name, label in (("old_divisor", "old divisor"), ("other_order", "corrected, another order of the same answers")):
        rows = rd(os.path.join(REP, f"{rule}_s1", f"bug_check_{name}.jsonl.gz"))
        d = paired(corrected, rows)
        row[name] = {"accuracy": acc(rows), "vs_corrected": d, "weights": b[name]["difference_from_corrected"]}
        L.append(f"| {label} | {pct(acc(rows))} | {gain_txt(d)} | {b[name]['difference_from_corrected']['entries_changed']:,} |")
    L.append("")
    S["bug_check"][rule] = row

# ------------------------------------------------------------------ how far the weights moved
L += ["## 5. How far the weights moved in each round", "",
      "Relative L2 is the size of the change divided by the size of the weights before it. 'After rounding' counts the weights "
      "still different once the float32 update is rounded to the bfloat16 the model runs in.", "",
      "| rule | seed | round | steps | moved by the update | still moved after rounding | relative L2 vs previous round | relative L2 vs original | largest gradient norm |",
      "|---|---|---|---|---|---|---|---|---|"]
for (rule, seed), t in sorted(T.items()):
    for row in t["traj"]["rounds"]:
        tr, wc = row["training"], row.get("weight_change")
        if not wc:
            continue
        n = tr["weights_total"]
        S["weights"].setdefault(f"{rule}_s{seed}", {})[str(row["round"])] = {
            "steps": tr["optimizer_steps"], "moved": tr["moved_by_float32_update"] / n, "after_rounding": tr["moved_after_rounding_to_bfloat16"] / n,
            "relative_l2_vs_previous": wc["vs_previous_round"]["relative_l2"], "relative_l2_vs_original": wc["vs_original"]["relative_l2"],
            "changed_vs_original": wc["vs_original"]["entries_changed"] / wc["vs_original"]["entries_total"], "grad_norms": tr["grad_norms_before_clipping"]}
        L.append(f"| {rule.split('_')[0]} | {seed} | {row['round']} | {tr['optimizer_steps']} | {100 * tr['moved_by_float32_update'] / n:.1f}% | "
                 f"{100 * tr['moved_after_rounding_to_bfloat16'] / n:.1f}% | {wc['vs_previous_round']['relative_l2']:.5f} | {wc['vs_original']['relative_l2']:.5f} | "
                 f"{max(tr['grad_norms_before_clipping']):.2f} |")
L.append("")

# ------------------------------------------------------------------ predictions (PREREG.md section 7)
C2, C1 = RULES
c2 = sorted(s for r, s in T if r == C2)
c1 = sorted(s for r, s in T if r == C1)
P = []


def verdict(name, ok, text):
    P.append((name, ok, text))


verdict("R0", abs(acc(old_base) - 0.105) <= 0.03 and abs(acc(old_astra) - 0.455) <= 0.03,
        f"unedited {pct(acc(old_base))}% (main run 10.5%), positive control {pct(acc(old_astra))}% (main run 45.5%)")
if len(c2) == 3 and all(3 in T[(C2, s)]["old"] for s in c2):
    gs = {s: paired(old_base, T[(C2, s)]["old"][3]) for s in c2}
    m = statistics.mean(acc(T[(C2, s)]["old"][3]) for s in c2)
    verdict("R1", all(g["gain"] >= 0.15 and (g["z"] or 0) >= 2 for g in gs.values()) and abs(m - 0.445) <= 0.10,
            "gain after round 3: " + ", ".join(f"seed {s} {gain_txt(g)}" for s, g in gs.items()) + f"; mean accuracy {pct(m)}% (main run 44.5%)")
    if all(str(s) in S["rounds_3_to_6"].get(C2, {}) for s in c2):
        ds = {s: S["rounds_3_to_6"][C2][str(s)]["all_400"] for s in c2}
        md = statistics.mean(d["gain"] for d in ds.values())
        verdict("R2", md < 0.05 and not any((d["z"] or 0) >= 2 and d["gain"] > 0 for d in ds.values()),
                "round 6 minus round 3 on all 400: " + ", ".join(f"seed {s} {gain_txt(d)}" for s, d in ds.items()) + f"; mean {pct(md, True)} points")
    else:
        verdict("R2", None, "not all C2 seeds reached round 6")
    if all(6 in T[(C2, s)]["old"] for s in c2):
        es = {s: ending(T[(C2, s)]["old"][6]) for s in c2}
        base_share = ending(old_base)["right_among_finished"]
        verdict("R3", all(e["finished_wrong"] >= 6 and e["right_among_finished"] < base_share for e in es.values()),
                "after round 6: " + ", ".join(f"seed {s} {e['finished_wrong']} finished wrong, {pct(e['right_among_finished'])}% of finished right" for s, e in es.items())
                + f"; unedited {ending(old_base)['finished_wrong']} and {pct(base_share)}%")
    else:
        verdict("R3", None, "not all C2 seeds reached round 6")
    fr = {s: paired(fresh_base, T[(C2, s)]["fresh"][3]) for s in c2 if 3 in T[(C2, s)]["fresh"]}
    verdict("R6", len(fr) == 3 and all(g["gain"] >= 0.15 and (g["z"] or 0) >= 2 for g in fr.values()),
            "fresh problems after round 3: " + ", ".join(f"seed {s} {gain_txt(g)}" for s, g in fr.items()))
else:
    for k in ("R1", "R2", "R3", "R6"):
        verdict(k, None, "C2 has not finished")
if len(c1) == 3 and len(c2) == 3 and all(3 in T[(C1, s)]["old"] for s in c1) and all(3 in T[(C2, s)]["old"] for s in c2):
    a1, a2 = [acc(T[(C1, s)]["old"][3]) for s in c1], [acc(T[(C2, s)]["old"][3]) for s in c2]
    verdict("R4", max(a1) - min(a1) > max(a2) - min(a2),
            f"range after round 3: C1 {100 * (max(a1) - min(a1)):.1f} points ({', '.join(pct(x) for x in a1)}), C2 {100 * (max(a2) - min(a2)):.1f} points ({', '.join(pct(x) for x in a2)})")
else:
    verdict("R4", None, "not all trajectories reached round 3")
if len(c1) == 3 and len(c2) == 3 and all(6 in T[(C1, s)]["old"] for s in c1) and all(6 in T[(C2, s)]["old"] for s in c2):
    m1, m2 = [statistics.mean(acc(T[(r, s)]["old"][6]) for s in (1, 2, 3)) for r in (C1, C2)]
    verdict("R5", m1 < m2, f"mean after round 6: C1 {pct(m1)}%, C2 {pct(m2)}%")
else:
    verdict("R5", None, "not all trajectories reached round 6")
if all(rule in S["bug_check"] for rule in RULES):
    ds = {rule: S["bug_check"][rule]["old_divisor"]["vs_corrected"] for rule in RULES}
    verdict("R7", all(abs(d["gain"]) < 2 * d["se"] or d["gain"] == 0 for d in ds.values()),
            "old divisor minus corrected: " + ", ".join(f"{rule.split('_')[0]} {gain_txt(d)}" for rule, d in ds.items()))
else:
    verdict("R7", None, "the check has not finished for both rules")
P.sort(key=lambda x: x[0])
L += ["## 6. Predictions (PREREG.md section 7), checked by this script", "", "| prediction | verdict | numbers |", "|---|---|---|"]
L += [f"| {k} | {'not decidable yet' if ok is None else ('held' if ok else 'did not hold')} | {txt} |" for k, ok, txt in P]
S["predictions"] = {k: {"held": ok, "numbers": txt} for k, ok, txt in P}
keeps = {}
for rule in RULES:
    ds = S["rounds_3_to_6"].get(rule, {})
    if len(ds) == 3:
        keeps[rule] = sum((d["all_400"]["z"] or 0) >= 2 and d["all_400"]["gain"] > 0 for d in ds.values())
S["keeps_improving_seeds"] = keeps
L += ["", "- 'Keeps improving' (at least 2 of a rule's 3 seeds have round 6 above round 3 by z >= 2 on the 400 problems): " +
      ("; ".join(f"{rule.split('_')[0]}: {'yes' if n >= 2 else 'no'} ({n} of 3 seeds)" for rule, n in keeps.items()) or "not decidable yet"), ""]

# ------------------------------------------------------------------ figures: accuracy by round, one panel per rule
try:
    import matplotlib
    matplotlib.use("Agg")
    import matplotlib.pyplot as plt
except ImportError:
    plt = None
THEMES = {"light": {"bg": "#fcfcfb", "ink": "#1a1a19", "muted": "#6b6b66", "grid": "#e4e4df", "series": ["#2a78d6", "#eb6834", "#1baf7a"]},
          "dark": {"bg": "#1a1a19", "ink": "#f4f4f0", "muted": "#a3a39d", "grid": "#34342f", "series": ["#3987e5", "#d95926", "#199e70"]}}
if plt and T:
    for mode, th in THEMES.items():
        fig, axes = plt.subplots(1, 2, figsize=(11.5, 5.2), sharey=True, facecolor=th["bg"])
        for ax, rule in zip(axes, RULES):
            ax.set_facecolor(th["bg"])
            ax.axhline(100 * acc(old_astra), color=th["muted"], lw=1.2, ls=(0, (2, 2)))
            ax.text(0.05, 100 * acc(old_astra) + 1.0, f"positive control {pct(acc(old_astra))}%", color=th["muted"], fontsize=9.5)
            xs = list(range(len(main_line[rule])))
            ax.plot(xs, [100 * v for v in main_line[rule]], color=th["muted"], lw=1.5, ls=(0, (5, 3)), marker="o", ms=4, label="main run (old divisor)", zorder=2)
            for i, seed in enumerate((1, 2, 3)):
                if (rule, seed) not in T:
                    continue
                t = T[(rule, seed)]
                ys = [100 * acc(old_base)] + [100 * acc(t["old"][r]) for r in t["rounds"]]
                x = [0] + t["rounds"]
                ax.plot(x, ys, color=th["series"][i], lw=2, marker="o", ms=5.5, label=f"seed {seed}", zorder=3,
                        markeredgecolor=th["bg"], markeredgewidth=1.2)
                ax.annotate(f"{ys[-1]:.1f}", (x[-1], ys[-1]), xytext=(7, 0), textcoords="offset points", va="center", color=th["ink"], fontsize=9.5)
            ax.set_title(SHORT[rule], color=th["ink"], fontsize=12, loc="left")
            ax.set_xlabel("round", color=th["muted"])
            ax.set_xlim(-0.2, 6.6)
            ax.set_xticks(range(0, 7))
            ax.set_ylim(0, 70)
            ax.grid(axis="y", color=th["grid"], lw=0.8)
            ax.tick_params(colors=th["muted"], length=0)
            for sp in ax.spines.values():
                sp.set_visible(False)
            ax.legend(loc="upper center", bbox_to_anchor=(0.5, -0.14), ncol=4, frameon=False, labelcolor=th["ink"], fontsize=9.5)
        axes[0].set_ylabel("test accuracy on the 200 old problems (%)", color=th["muted"])
        fig.tight_layout()
        fig.savefig(os.path.join(RES, "figures", f"replication_by_round_{mode}.png"), dpi=150, facecolor=th["bg"])
        plt.close(fig)

with open(os.path.join(RES, "RESULTS.md"), "w", encoding="utf-8", newline="\n") as f:
    f.write("\n".join(L) + "\n")
json.dump(S, open(os.path.join(RES, "summary.json"), "w", encoding="utf-8"), indent=1)
print("wrote", os.path.join(RES, "RESULTS.md"), "trajectories:", sorted(f"{r.split('_')[0]}_s{s}" for r, s in T))
