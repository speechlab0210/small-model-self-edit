"""Builds results/RESULTS.md (every number of the write-up), results/summary.json and the figures from the raw
outputs in <out>. Nothing is typed by hand: re-run this script on the raw outputs to check any number.

  python analysis/make_report.py <out dir> <results dir>
"""
import glob
import gzip
import json
import math
import os
import sys

OUT, RES = sys.argv[1], sys.argv[2]
os.makedirs(os.path.join(RES, "figures"), exist_ok=True)


def jload(p, default=None):
    try:
        return json.load(open(p, encoding="utf-8"))
    except (OSError, ValueError):
        return default


def recs(p):
    with gzip.open(p, "rt", encoding="utf-8") as f:
        return [json.loads(x) for x in f]


def acc(rs, src=None):
    rs = [r for r in rs if src is None or r["source"] == src]
    return sum(r["correct"] for r in rs) / len(rs) if rs else float("nan")


def cut(rs, src=None):
    rs = [r for r in rs if src is None or r["source"] == src]
    return sum(r["finish"] == "length" for r in rs) / len(rs) if rs else float("nan")


def paired(a, b):
    m = {r["id"]: r["correct"] for r in a}
    d = [r["correct"] - m[r["id"]] for r in b if r["id"] in m]
    n = len(d)
    mu = sum(d) / n
    sd = math.sqrt(sum((x - mu) ** 2 for x in d) / (n - 1)) if n > 1 else 0.0
    se = sd / math.sqrt(n)
    return {"n": n, "gain": mu, "se": se, "z": mu / se if se else 0.0, "rescues": d.count(1), "losses": d.count(-1)}


def pct(x):
    return "n/a" if x is None or (isinstance(x, float) and math.isnan(x)) else f"{100 * x:.1f}"


S = {"tests": {}, "arm_a": {}, "arm_b": {}, "arm_c": {}}
lines = ["# RESULTS (generated by analysis/make_report.py from the raw outputs; do not edit by hand)", ""]

# ------------------------------------------------------------------ test set: every evaluated model
tdir = os.path.join(OUT, "test")
base_p = os.path.join(tdir, "unedited.jsonl.gz")
base = recs(base_p) if os.path.exists(base_p) else None
rows = []
named = {}
for p in sorted(glob.glob(os.path.join(tdir, "*.jsonl.gz"))):
    named[os.path.basename(p)[:-9]] = recs(p)
for d in sorted(glob.glob(os.path.join(OUT, "arm_b", "B*"))):
    for p in sorted(glob.glob(os.path.join(d, "test_round*.jsonl.gz"))):
        named[f"{os.path.basename(d)}_after_round{os.path.basename(p)[10:-9]}"] = recs(p)
for d in sorted(glob.glob(os.path.join(OUT, "arm_c", "C*"))):
    for p in sorted(glob.glob(os.path.join(d, "test_round*.jsonl.gz"))):
        named[f"{os.path.basename(d)}_after_round{os.path.basename(p)[10:-9]}"] = recs(p)
order = {"unedited": 0, "astra_positive_control": 1}
named = dict(sorted(named.items(), key=lambda kv: (order.get(kv[0], 2), kv[0])))
lines += ["## 1. Test set (100 MATH-500 + 100 GSM8K, thinking on, at most 16,384 tokens, paired seeds)", "",
          "| model | MATH-500 acc | GSM8K acc | all acc | cut at cap | mean tokens | paired gain vs unedited (SE) | z | wrong->right / right->wrong |",
          "|---|---|---|---|---|---|---|---|---|"]
for name, rs in named.items():
    pg = paired(base, rs) if base else None
    mt = sum(r["tokens"] for r in rs) / len(rs)
    S["tests"][name] = {"math500": acc(rs, "math500"), "gsm8k": acc(rs, "gsm8k"), "all": acc(rs), "cut": cut(rs),
                        "mean_tokens": mt, "paired": pg}
    lines.append(f"| {name} | {pct(acc(rs, 'math500'))} | {pct(acc(rs, 'gsm8k'))} | {pct(acc(rs))} | {pct(cut(rs))} | "
                 f"{mt:,.0f} | {pct(pg['gain']) if pg else '-'} ({pct(pg['se']) if pg else '-'}) | "
                 f"{pg['z']:.2f} | {pg['rescues']} / {pg['losses']} |" if pg else
                 f"| {name} | {pct(acc(rs, 'math500'))} | {pct(acc(rs, 'gsm8k'))} | {pct(acc(rs))} | {pct(cut(rs))} | {mt:,.0f} | - | - | - |")
lines.append("")

# ------------------------------------------------------------------ sanity / positive control
san = jload(os.path.join(OUT, "sanity.json"))
if san:
    S["sanity"] = san
    g = san.get("greedy", {})
    lines += ["## 2. Checks of the weight-update mechanism", "",
              f"- greedy answer restored after an edit is undone: {g.get('restored_equals_original')}; zeroing layer 15's "
              f"MLP output changes the answer: {g.get('zeroed_changes_output')}",
              f"- max |log-prob difference| between the two engines on the unedited weights: "
              f"{san.get('hf_vs_vllm_original', [None])[0]}",
              "- after adding 5% noise to one tensor of each kind, the same difference per kind: "
              + ", ".join(f"{k} {v['max_abs_logprob_diff'][0]:.3f}" for k, v in sorted(san.get("hf_vs_vllm_after_noise_by_tensor_type", {}).items())),
              ""]
ac = jload(os.path.join(OUT, "astra_edit_check.json"))
if ac:
    S["astra_edit_check"] = ac
    lines += [f"- the positive-control checkpoint differs from the base in {len(ac['tensors_that_differ'])} tensors, "
              f"{ac['changed_entries']:,} entries: {', '.join(sorted(ac['tensors_that_differ']))}", ""]

# ------------------------------------------------------------------ Arm B
bdir = os.path.join(OUT, "arm_b")
di = jload(os.path.join(bdir, "directions_info.json"))
tb = jload(os.path.join(bdir, "round1_table.json"))
if di or tb:
    lines += ["## 3. Arm B (choose one of 8 edits, 6 rounds)", ""]
if di:
    S["arm_b"]["directions"] = di
    ds = di["diag_summary"]["all"]
    lines += [f"- looping direction from {di['looping_texts']} looping and {di['productive_texts']} productive answers "
              f"(fallback used: productive side {di['productive_fallback']}, looping side {di.get('looping_fallback_all_cut')}); "
              f"the unedited model on the {ds['n']} diagnostic practice "
              f"problems: {ds['correct']} correct, {ds['cut']} cut at 8,192 tokens ({ds['cut_looping']} of them looping)", ""]
if tb:
    S["arm_b"]["round1_table"] = tb
    lines += ["Round 1: every candidate measured on the same 64 practice problems (paired with the unedited model)", "",
              "| candidate | kind | layer | strength / head | dev gain (SE) | accepted by referee | picked by self (of 20) |",
              "|---|---|---|---|---|---|---|"]
    picks = [s["pick"] for s in tb["self_samples"]]
    for j, c in enumerate(tb["candidates"]):
        p = c["paired"]
        lines.append(f"| {c['cid']} | {c['kind']} | {c['layer']} | {c.get('alpha', c.get('head'))} | {pct(p['gain'])} ({pct(p['se'])}) | "
                     f"{c['accept']} | {picks.count(j)} |")
    valid = [x for x in picks if x is not None]
    loop_share = sum(tb["candidates"][x]["kind"].startswith("loop") for x in valid) / len(valid) if valid else float("nan")
    mean_all = sum(c["paired"]["gain"] for c in tb["candidates"]) / len(tb["candidates"])
    mean_pick = sum(tb["candidates"][x]["paired"]["gain"] for x in valid) / len(valid) if valid else float("nan")
    first_pos = {}
    for s in tb["self_samples"]:
        if s["number"] is not None:
            first_pos[s["number"]] = first_pos.get(s["number"], 0) + 1
    S["arm_b"]["choice_quality"] = {"valid": len(valid), "samples": len(picks), "loop_share": loop_share,
                                   "mean_gain_of_picks": mean_pick, "mean_gain_all": mean_all,
                                   "answered_number_counts": first_pos}
    lines += ["", f"- self chooser: {len(valid)} of {len(picks)} samples gave a usable number; {pct(loop_share)}% of "
              f"them picked a 'looping direction' option (menu share 62.5%); mean dev gain of its picks {pct(mean_pick)} vs "
              f"{pct(mean_all)} for all 8 candidates; numbers it answered (position in the shuffled list): {dict(sorted(first_pos.items()))}", ""]
for d in sorted(glob.glob(os.path.join(bdir, "B*"))):
    t = jload(os.path.join(d, "trajectory.json"))
    if not t:
        continue
    name = os.path.basename(d)
    S["arm_b"][name] = t
    lines += [f"### {name} (chooser: {t['chooser']}, referee: {t['referee']})", "",
              "| round | chosen | accepted | dev check (gain, SE) |", "|---|---|---|---|"]
    for r in t["rounds"]:
        ch = r.get("chosen")
        desc = f"{ch['kind']} L{ch['layer']} {ch.get('alpha', ch.get('head'))}" if ch else (r.get("result") or "-")
        p = r.get("paired") or r.get("paired_if_measured")
        lines.append(f"| {r['round']} | {desc} | {r.get('accepted')} | {(pct(p['gain']) + ' (' + pct(p['se']) + ')') if p else '-'} |")
    for k, v in sorted(t.get("tests", {}).items()):
        p = v.get("paired") or {}
        lines.append(f"\n- test after round {k}: gain {pct(p.get('gain'))} (SE {pct(p.get('se'))})" + (f" [{v['same_as']}]" if v.get("same_as") else ""))
    lines.append(f"- final edited tensors: {t.get('final_edits')}")
    lines.append("")

# ------------------------------------------------------------------ Arm A
adirs = sorted(glob.glob(os.path.join(OUT, "arm_a", "*_s*")))
if adirs:
    lines += ["## 4. Arm A (the blog post's tools, the small model as its own editor)", "",
              "| run | turns | python blocks (ran without error) | forward blocks (ran) | no block | cut while thinking | save_edit calls | weights changed at the end | test gain (SE) |",
              "|---|---|---|---|---|---|---|---|---|"]
for d in adirs:
    s = jload(os.path.join(d, "summary.json"))
    if not s:
        continue
    name = os.path.basename(d)
    S["arm_a"][name] = s
    tp = (s.get("test") or {}).get("paired") or {}
    lines.append(f"| {name} | {s['turns']} | {s['python_blocks']} ({s['python_ok']}) | {s['forward_blocks']} ({s['forward_ok']}) | "
                 f"{s['no_block']} | {s['cut_while_thinking']} | {s['save_edit_calls']} | {s['final_changed_weights']:,} | "
                 f"{pct(tp.get('gain'))} ({pct(tp.get('se'))}) |")
hc = jload(os.path.join(OUT, "arm_a", "harness_check.json"))
if hc:
    S["arm_a"]["harness_check_ok"] = hc.get("ok")
    lines.append(f"\nTool check before the runs (a scripted editor, not the model, used every tool once): ok = {hc.get('ok')}; "
                 f"the saved edit changed {hc.get('save_edit', {}).get('engine_changed_entries')} weights in the engine, and "
                 f"dropping it left {hc.get('drop_edit', {}).get('engine_edits_after')} edited tensors.")
if adirs or hc:
    lines.append("")

# ------------------------------------------------------------------ Arm C
for d in sorted(glob.glob(os.path.join(OUT, "arm_c", "C*"))):
    t = jload(os.path.join(d, "trajectory.json"))
    if not t:
        continue
    name = os.path.basename(d)
    S["arm_c"][name] = t
    lines += [f"## 5. Arm C: {name}", "", "| round | practice answers correct / cut | kept for training | of them correct | train loss first -> last | test gain (SE) |",
              "|---|---|---|---|---|---|"]
    for r in t["rounds"]:
        g = r["generated"]
        p = r["test"]["paired"]
        lines.append(f"| {r['round']} | {g['correct']} / {g['cut']} of {g['n']} | {r['kept']} | {r['kept_correct']} | "
                     f"{r.get('train_loss_first', '-')} -> {r.get('train_loss_last', '-')} | {pct(p['gain'])} ({pct(p['se'])}) |")
    lines.append("")

open(os.path.join(RES, "RESULTS.md"), "w", encoding="utf-8").write("\n".join(lines) + "\n")
json.dump(S, open(os.path.join(RES, "summary.json"), "w", encoding="utf-8"), indent=1, default=str)

# ------------------------------------------------------------------ figures
try:
    import matplotlib
    matplotlib.use("Agg")
    import matplotlib.pyplot as plt
except ImportError:
    plt = None
if plt and S["tests"]:
    names = list(S["tests"])
    fig, ax = plt.subplots(figsize=(max(6, 0.55 * len(names) + 2), 4))
    vals = [100 * S["tests"][n]["all"] for n in names]
    errs = [100 * (S["tests"][n]["paired"] or {}).get("se", 0) for n in names]
    ax.bar(range(len(names)), vals, yerr=errs, color="#4C72B0", capsize=3)
    ax.set_xticks(range(len(names)))
    ax.set_xticklabels(names, rotation=60, ha="right", fontsize=8)
    ax.set_ylabel("test accuracy (%), 200 problems")
    ax.set_title("Every evaluated model on the same 200 test problems")
    fig.tight_layout()
    fig.savefig(os.path.join(RES, "figures", "test_accuracy.png"), dpi=150)
print("\n".join(lines))
